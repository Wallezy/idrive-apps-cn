'use strict';
const assert = require('assert');
const { DisplayFocus } = require('./broker');
let time = 0;
const b = new DisplayFocus({ metrics: ['cluster.primary', 'hud.primary'], themes: ['cluster.primary'], redline: ['hud.primary'] }, () => time);
const metrics = b.connect('metrics'), themes = b.connect('themes'), redline = b.connect('redline');
b.request(metrics, 'cluster.primary'); b.request(themes, 'cluster.primary');
assert.strictEqual(b.status('cluster.primary').reason, 'stock');
b.select('cluster.primary', 'metrics');
const grant = b.drain().find(e => e.event === 'grant');
assert(b.permitted(metrics, grant.zone, grant.lease));
b.select('cluster.primary', 'themes');
const hide = b.drain()[0];
assert.strictEqual(hide.event, 'hide');
assert(!b.permitted(metrics, grant.zone, grant.lease));
assert.strictEqual(b.status('cluster.primary').active.session, metrics);
assert(!b.hidden(hide.zone, hide.epoch - 1), 'stale ack must not release a newer lease');
time = 2001; b.tick();
assert.strictEqual(b.status(hide.zone).reason, 'release-timeout');
assert.strictEqual(b.drain().length, 0, 'timeout must not grant another app over stale pixels');
b.hidden(hide.zone, hide.epoch);
assert.strictEqual(b.drain()[0].session, themes);
b.safety('cluster.primary', true);
const safetyHide = b.drain()[0];
b.hidden(safetyHide.zone, safetyHide.epoch);
assert.strictEqual(b.status(safetyHide.zone).reason, 'oem-safety');
assert.strictEqual(b.drain().length, 0);
b.safety(safetyHide.zone, false);
assert.strictEqual(b.drain()[0].session, themes, 'restore selected app after OEM alert');
b.request(redline, 'hud.primary'); b.select('hud.primary', 'redline');
b.drain(); b.legacy('hud.primary', true);
const legacyHide = b.drain()[0]; b.hidden(legacyHide.zone, legacyHide.epoch);
assert.strictEqual(b.status('hud.primary').reason, 'legacy-unmanaged');
assert.strictEqual(b.drain().length, 0);
assert.throws(() => b.request(themes, 'hud.primary'), /undeclared/);
assert.throws(() => b.select('cluster.primary', 'redline'), /invalid/);
assert.throws(() => b.connect('unknown'), /unregistered/);
const duplicate = b.connect('metrics');
assert.throws(() => b.request(duplicate, 'cluster.primary'), /duplicate/);
time = 6001; b.tick();
const expiryHide = b.drain().find(e => e.zone === 'cluster.primary');
assert(expiryHide, 'expired app must be hidden even without voluntary release');
b.hidden(expiryHide.zone, expiryHide.epoch);
assert.strictEqual(b.status('cluster.primary').active, null);
assert.throws(() => b.heartbeat(themes), /expired/);
const fresh = b.connect('themes'); b.request(fresh, 'cluster.primary');
assert.notStrictEqual(fresh, themes); b.drain();
b.restoreStock();
for (const e of b.drain()) b.hidden(e.zone, e.epoch);
assert.strictEqual(b.status('cluster.primary').reason, 'stock');
assert.strictEqual(b.status('cluster.primary').active, null);
console.log('Display focus prototype: handover, stale ack, timeout, OEM priority, legacy block, capabilities, lease expiry, reconnect and stock restoration passed');
